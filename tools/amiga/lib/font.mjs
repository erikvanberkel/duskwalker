// Returns { bits: Uint8Array(96*8), advance: Uint8Array(96) } for characters 32..127.
export function buildFont() {
  const bits = new Uint8Array(96 * 8), advance = new Uint8Array(96);
  for (let c = 32; c < 128; c++) {
    let ch = String.fromCharCode(c);
    if (ch >= 'a' && ch <= 'z') ch = ch.toUpperCase();
    const rows = G[ch] ?? (c === 32 ? [] : G['?']);
    let w = 0;
    rows.forEach((r, y) => {
      for (let x = 0; x < r.length; x++) if (r[x] === '#') { bits[(c - 32) * 8 + y] |= 0x80 >> x; w = Math.max(w, x + 1); }
    });
    advance[c - 32] = c === 32 ? 4 : w + 1;
  }
  return { bits, advance };
}

// Render a string into a mono bitmap (for pre-rendered small text images)
export function renderText(font, s, scale = 1) {
  let w = 0;
  for (const ch of s) w += font.advance[(ch.charCodeAt(0) - 32) & 127] || 4;
  const W = w * scale, H = 8 * scale, px = new Uint8Array(W * H);
  let x = 0;
  for (const ch of s) {
    const c = (ch.charCodeAt(0) - 32) & 127;
    for (let y = 0; y < 8; y++)
      for (let b = 0; b < 8; b++)
        if (font.bits[c * 8 + y] & (0x80 >> b))
          for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) px[(y * scale + sy) * W + (x + b) * scale + sx] = 1;
    x += font.advance[c] || 4;
  }
  return { w: W, h: H, px };
}
